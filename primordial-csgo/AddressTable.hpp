	inline bool Fix()
	{
		for (const AddressInfo& addressInfo : g_addresses)
		{
			HMODULE moduleBase = image::WaitForModule(addressInfo.moduleName.c_str());
			if (moduleBase == nullptr)
			{
				image::Log("FAIL: WaitForModule(\"%s\")\n", addressInfo.moduleName.c_str());
				return false;
			}

			std::uintptr_t encryptionKey = *reinterpret_cast<std::uintptr_t*>(reinterpret_cast<std::uintptr_t>(image::g_base) + addressInfo.rva + sizeof(std::uintptr_t));
			*reinterpret_cast<std::uintptr_t*>(reinterpret_cast<std::uintptr_t>(image::g_base) + addressInfo.rva) =
				(reinterpret_cast<std::uintptr_t>(moduleBase) + addressInfo.moduleRva) ^ encryptionKey;
		}

		image::Log("OK: %zu addresses resolved\n", g_addresses.size());
		return true;
	}
