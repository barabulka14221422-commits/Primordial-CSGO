	inline bool Fix()
	{
		fp_wolfssl_read = reinterpret_cast<fpt_wolfssl_read>(reinterpret_cast<std::uintptr_t>(image::g_base) + 0xCE1A0);
		fp_wolfssl_write = reinterpret_cast<fpt_wolfssl_write>(reinterpret_cast<std::uintptr_t>(image::g_base) + 0xCE140);
		fp_wolfssl_connect = reinterpret_cast<fpt_wolfssl_connect>(reinterpret_cast<std::uintptr_t>(image::g_base) + 0xD0D30);
		return MH_CreateHookApiEx(L"ws2_32.dll", "connect", d_connect, reinterpret_cast<LPVOID*>(&o_connect), reinterpret_cast<LPVOID*>(&fp_connect)) == MH_OK &&
			MH_CreateHook(fp_wolfssl_read, d_wolfssl_read, nullptr) == MH_OK &&
			MH_CreateHook(fp_wolfssl_write, d_wolfssl_write, nullptr) == MH_OK &&
			MH_CreateHook(fp_wolfssl_connect, d_wolfssl_connect, nullptr) == MH_OK &&
			MH_EnableHook(fp_connect) == MH_OK &&
			MH_EnableHook(fp_wolfssl_read) == MH_OK &&
			MH_EnableHook(fp_wolfssl_write) == MH_OK &&
			MH_EnableHook(fp_wolfssl_connect) == MH_OK;
	}
